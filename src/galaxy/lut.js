// stars in a wedge; 0 for out-of-range indices.
export function wedgeStars(s, b) {
  const row = LUT[s];
  if (!row) return 0;
  return row[b] || 0;
}

// inclusive radial band [near, far] in ly for ring b.
export function wedgeBand(b) {
  return [b * BIN_LY, (b + 1) * BIN_LY];
}

// the most populous wedge — used to size the launcher's charge capacity.
export const MAX_WEDGE_STARS = LUT.reduce(
  (m, row) => Math.max(m, ...row),
  0
);

// total stars across the whole modelled frontier (~3.3e11, the galaxy).
export const TOTAL_STARS = LUT.reduce((sum, row) => sum + row.reduce((a, v) => a + v, 0), 0);
